"""
PDF generation service using fpdf2.

Generates CMA reports as PDF files saved to /tmp/ and returns a local URL path.
"""

import os
import tempfile
from datetime import datetime
from typing import Any, Dict, List


def generate_cma_pdf(
    address: str,
    comps: List[Dict[str, Any]],
    summary: str,
    estimated_value: float,
    price_range_low: float,
    price_range_high: float,
) -> str:
    """
    Generate a CMA PDF report.

    Returns:
        File path to the generated PDF.
    """
    try:
        from fpdf import FPDF

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        # ── Header ──────────────────────────────────────────────────────────
        pdf.set_font("Helvetica", "B", 20)
        pdf.set_fill_color(30, 80, 160)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(0, 14, "  Real Estate AI — CMA Report", fill=True, ln=True)

        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 6, f"  Generated: {datetime.now().strftime('%B %d, %Y')}", ln=True)
        pdf.ln(4)

        # ── Subject Property ────────────────────────────────────────────────
        pdf.set_font("Helvetica", "B", 13)
        pdf.cell(0, 8, "Subject Property", ln=True)
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 7, address, ln=True)
        pdf.ln(3)

        # ── Valuation Box ───────────────────────────────────────────────────
        pdf.set_fill_color(240, 248, 255)
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, "Estimated Market Value", fill=True, ln=True)
        pdf.set_font("Helvetica", "B", 18)
        pdf.set_text_color(30, 80, 160)
        pdf.cell(0, 10, f"  ${estimated_value:,.0f}", ln=True)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(80, 80, 80)
        pdf.cell(0, 6, f"  Range: ${price_range_low:,.0f} – ${price_range_high:,.0f}", ln=True)
        pdf.set_text_color(0, 0, 0)
        pdf.ln(4)

        # ── Summary ─────────────────────────────────────────────────────────
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, "Market Analysis Summary", ln=True)
        pdf.set_font("Helvetica", "", 10)
        pdf.multi_cell(0, 6, summary)
        pdf.ln(4)

        # ── Comps Table ─────────────────────────────────────────────────────
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, "Comparable Sales", ln=True)

        # Table header
        pdf.set_fill_color(30, 80, 160)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 9)
        col_widths = [70, 28, 18, 14, 14, 28]
        headers = ["Address", "Price", "SqFt", "Bed", "Bath", "Sold Date"]
        for w, h in zip(col_widths, headers):
            pdf.cell(w, 7, h, border=0, fill=True)
        pdf.ln()

        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "", 9)
        for i, comp in enumerate(comps):
            fill = i % 2 == 0
            pdf.set_fill_color(245, 245, 245) if fill else pdf.set_fill_color(255, 255, 255)
            row = [
                str(comp.get("address", ""))[:38],
                f"${comp.get('price', 0):,.0f}",
                str(comp.get("sqft", "")),
                str(comp.get("beds", "")),
                str(comp.get("baths", "")),
                str(comp.get("sold_date", "")),
            ]
            for w, val in zip(col_widths, row):
                pdf.cell(w, 6, val, border=0, fill=fill)
            pdf.ln()

        pdf.ln(6)

        # ── Footer ──────────────────────────────────────────────────────────
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(120, 120, 120)
        pdf.cell(0, 5, "Generated by Real Estate AI Business-in-a-Box | listing-pilot.app", ln=True)

        # Save to temp file
        out_dir = os.getenv("PDF_OUTPUT_DIR", tempfile.gettempdir())
        filename = f"cma_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
        filepath = os.path.join(out_dir, filename)
        pdf.output(filepath)
        return filepath

    except ImportError:
        # fpdf2 not installed — return placeholder path
        return "/tmp/cma_placeholder.pdf"
    except Exception as exc:
        print(f"[pdf_generator] Error generating PDF: {exc}")
        return "/tmp/cma_error.pdf"
